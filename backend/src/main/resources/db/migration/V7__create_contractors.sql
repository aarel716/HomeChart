CREATE TABLE contractors
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id     BIGINT                                  NOT NULL,
    category_id BIGINT                                  NOT NULL,
    name        VARCHAR(100)                            NOT NULL,
    phone       VARCHAR(30),
    email       VARCHAR(254),
    is_active   BOOLEAN                                 NOT NULL DEFAULT TRUE,

    CONSTRAINT pk_contractors PRIMARY KEY (id),

    CONSTRAINT fk_contractors_user
        FOREIGN KEY (user_id)
            REFERENCES users (id),

    CONSTRAINT fk_contractors_category
        FOREIGN KEY (category_id)
            REFERENCES maintenance_categories (id)
);

ALTER TABLE maintenance_records
    ADD COLUMN contractor_id BIGINT;

ALTER TABLE maintenance_records
    ADD CONSTRAINT fk_maintenance_records_contractor
        FOREIGN KEY (contractor_id)
            REFERENCES contractors (id);

CREATE INDEX idx_contractors_user_id
    ON contractors (user_id);

CREATE INDEX idx_maintenance_records_contractor_id
    ON maintenance_records (contractor_id);
